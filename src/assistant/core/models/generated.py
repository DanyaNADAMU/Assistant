"""Result model for AI-generated media (image / video)."""

import time
from enum import StrEnum
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field


class GeneratedMediaKind(StrEnum):
    IMAGE = "image"
    VIDEO = "video"


class GeneratedMedia(BaseModel):
    """A successfully generated media artifact (image or video)."""

    kind: GeneratedMediaKind
    content_bytes: bytes
    mime_type: str
    model_used: str
    prompt: str
    width: int | None = None
    height: int | None = None
    duration_seconds: float | None = None
    duration_sec: str | None = None  # video duration string, e.g. "5s"
    resolution: str | None = None  # video resolution, e.g. "720p"
    from_cache: bool = False
    elapsed_seconds: float = 0.0
    metadata: dict[str, Any] = Field(default_factory=dict)

    @property
    def default_extension(self) -> str:
        """Derive a sensible file extension from the mime type or content."""
        match self.mime_type.lower():
            case "image/png":
                return "png"
            case "image/webp":
                return "webp"
            case "image/jpeg" | "image/jpg":
                return "jpg"
            case "image/gif":
                return "gif"
            case "video/mp4" | "video/mpeg":
                return "mp4"
            case "video/webm":
                return "webm"
            case "video/quicktime":
                return "mov"
            case _:
                return "bin"

    def to_file(self, path: Path) -> Path:
        """Persist generated bytes to disk at the given path."""
        path.write_bytes(self.content_bytes)
        return path


class GeneratedMediaError(Exception):
    """Raised when a media generation backend fails."""

    def __init__(self, status_code: int, message: str) -> None:
        super().__init__(f"Media generation error [{status_code}]: {message}")
        self.status_code = status_code
        self.message = message

    @property
    def is_retryable(self) -> bool:
        """Rate limit (429) or transient server errors (5xx) are retryable."""
        return self.status_code == 429 or 500 <= self.status_code < 600


class GeneratedMediaResult(BaseModel):
    """Composed generation result returned to callers (bytes + optional file).

    Keeps both the raw bytes and a resolved output path so interfaces can
    either send the in-memory payload (Telegram) or write to disk (CLI).
    """

    media: GeneratedMedia
    file_path: Path | None = None
    started_at: float = Field(default_factory=time.time)
